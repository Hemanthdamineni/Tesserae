const ORACLE = {
  size: 4192,
  magic: 'feedfacf',
  cputype: 0x1000007,
  cpu: 'x86_64',
  filetype: 'MH_EXECUTE (executable)',
  ncmds: 8,
  sizeofcmds: 324,
  flags: 0x00200085,
};

function b64(s: string): Uint8Array {
  const bin = atob(s);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i += 1) out[i] = bin.charCodeAt(i);
  return out;
}

function fileOf(bytes: Uint8Array, name = 'x.bin'): File {
  const copy = new Uint8Array(bytes);
  return new File([copy.buffer as ArrayBuffer], name, { type: 'application/octet-stream' });
}

async function tableOf(
  f: File,
  options: Record<string, string | number | boolean> = {},
): Promise<{ headers: string[]; rows: string[][] }> {
  const r = await tool.run({ files: [f], options });
  return JSON.parse(r.report?.output ?? '{"rows":[]}') as { headers: string[]; rows: string[][] };
}

describe('mach-o-inspector', () => {
  it('declares on-device privacy and no network', () => {
    expect(tool.meta.privacy.processing).toBe('on-device');
    expect(tool.meta.privacy.network).toBe('none');
    expect(tool.meta.privacy.offline).toBe(true);
  });

  it('rejects a non-Mach-O file', async () => {
    await expect(tableOf(fileOf(new Uint8Array([1, 2, 3, 4]), 'bad.bin'))).rejects.toThrow(
      /Mach-O/,
    );
  });

  it('reads the summary view', async () => {
    const t = await tableOf(fileOf(b64(MACHO_B64)), { view: 'summary' });
    const m = new Map<string, string>(t.rows.map((r) => [r[0] ?? '', r[1] ?? '']));
    expect(m.get('File size')).toBe(`${ORACLE.size} B`);
    expect(m.get('Magic')).toBe('0xfeedfacf (MH_MAGIC_64)');
    expect(m.get('Endianness')).toBe('Little (native)');
    expect(m.get('Word size')).toBe('64-bit');
    expect(m.get('CPU type')).toContain('x86_64');
    expect(m.get('File type')).toContain('MH_EXECUTE');
    expect(m.get('Load commands')).toBe(String(ORACLE.ncmds));
    const flags = m.get('Flag names') ?? '';
    expect(flags).toContain('PIE');
    expect(flags).toContain('NOUNDEFS');
    expect(flags).toContain('TWOLEVEL');
    expect(flags).toContain('DYLDLINK');
  });

  it('lists all load commands', async () => {
    const t = await tableOf(fileOf(b64(MACHO_B64)), { view: 'commands' });
    const names = t.rows.map((r) => r[2] ?? '');
    for (const n of [
      'LC_SEGMENT_64',
      'LC_UUID',
      'LC_SYMTAB',
      'LC_LOAD_DYLINKER',
      'LC_LOAD_DYLIB',
      'LC_BUILD_VERSION',
      'LC_MAIN',
    ]) {
      expect(names).toContain(n);
    }
    // top-level command rows (those with a real # index) equal ncmds
    const top = t.rows.filter((r) => (r[0] ?? '') !== '');
    expect(top).toHaveLength(ORACLE.ncmds);
  });

  it('lists segments', async () => {
    const t = await tableOf(fileOf(b64(MACHO_B64)), { view: 'segments' });
    const segs = t.rows.map((r) => r[1] ?? '');
    expect(segs).toContain('__TEXT');
    expect(segs).toContain('__LINKEDIT');
    const text = t.rows.find((r) => (r[1] ?? '') === '__TEXT');
    expect(text?.[7]).toBe('r-x'); // init protection
  });

  it('reads dependencies', async () => {
    const t = await tableOf(fileOf(b64(MACHO_B64)), { view: 'dependencies' });
    const rows = t.rows.map((r) => (r[0] ?? '') + ' ' + (r[1] ?? ''));
    expect(rows).toContain('dylinker /usr/lib/dyld');
    expect(rows).toContain('dylib /usr/lib/libSystem.B.dylib');
  });

  it('reads build info', async () => {
    const t = await tableOf(fileOf(b64(MACHO_B64)), { view: 'build' });
    const m = new Map<string, string>(t.rows.map((r) => [r[0] ?? '', r[1] ?? '']));
    expect(m.get('Platform')).toBe('iOS Simulator');
    expect(m.get('Minimum OS')).toBe('11.0.0');
    expect(m.get('SDK')).toBe('13.0.0');
    expect(m.get('Entry offset')).toBe('0x1000');
    expect(m.get('Symbols')).toBe('1');
  });
});
