const ORACLE = {
  size: 2048,
  entries: 2,
  totalData: 6,
  names: ['hello.txt', 'dir/'],
};

function b64(s: string): Uint8Array {
  const bin = atob(s);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i += 1) out[i] = bin.charCodeAt(i);
  return out;
}

function fileOf(bytes: Uint8Array, name = 'x.tar'): File {
  const copy = new Uint8Array(bytes);
  return new File([copy.buffer as ArrayBuffer], name, { type: 'application/x-tar' });
}

async function tableOf(
  f: File,
  options: Record<string, string | number | boolean> = {},
): Promise<{ headers: string[]; rows: string[][] }> {
  const r = await tool.run({ files: [f], options });
  return JSON.parse(r.report?.output ?? '{"rows":[]}') as { headers: string[]; rows: string[][] };
}

describe('tar-inspector', () => {
  it('declares on-device privacy and no network', () => {
    expect(tool.meta.privacy.processing).toBe('on-device');
    expect(tool.meta.privacy.network).toBe('none');
    expect(tool.meta.privacy.offline).toBe(true);
  });

  it('rejects a non-tar file', async () => {
    const bad = new Uint8Array(512);
    bad[0] = 0x00;
    await expect(tableOf(fileOf(bad, 'bad.bin'))).rejects.toThrow(/tar/);
  });

  it('reads the summary view', async () => {
    const t = await tableOf(fileOf(b64(TAR_B64)), { view: 'summary' });
    const m = new Map<string, string>(t.rows.map((r) => [r[0] ?? '', r[1] ?? '']));
    expect(m.get('File size')).toBe('2048 B');
    expect(m.get('Archive format')).toBe('USTAR/POSIX');
    expect(m.get('Entries')).toBe('2');
    expect(m.get('Regular files')).toBe('1');
    expect(m.get('Directories')).toBe('1');
    expect(m.get('Total data size')).toBe('6 B');
    expect(m.get('Checksum errors')).toBe('0');
    expect(m.get('Zero terminator')).toBe('present');
  });

  it('lists the entries', async () => {
    const t = await tableOf(fileOf(b64(TAR_B64)), { view: 'entries' });
    expect(t.rows).toHaveLength(ORACLE.entries);
    const names = t.rows.map((r) => r[0] ?? '');
    expect(names[0]).toBe('hello.txt');
    expect(names[1]).toBe('dir/');
    expect(t.rows[0]?.[1]).toBe('file');
    expect(t.rows[1]?.[1]).toBe('directory');
  });
});
